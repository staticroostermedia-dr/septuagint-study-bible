#!/usr/bin/env python3
"""Latin-letter keys (transliteration) for NT-only headwords, in the same scheme as the LXX entries (STEPBible TBESG column 5).
1) TBESG's own transliteration when the TBESG entry for the same Strong's number has the same headword (accent-insensitive);
2) otherwise generated by the rules below, which reproduce TBESG's scheme (rough breathing written 'h' before the vowel that carries it:
   ὁ ho, εὑ ehu, υἱ uhi; ῥ rh; η ē, ω ō, χ ch, θ th, φ ph, ψ ps, ξ x, υ u; γγ gg, γκ gk (TBESG does not write the nasal n)).
Idempotent; run in site/. Usage: nt_translit.py TBESG_TXT [--selftest]"""
import json, re, sys, unicodedata, subprocess
MAP = {'α': 'a', 'β': 'b', 'γ': 'g', 'δ': 'd', 'ε': 'e', 'ζ': 'z', 'η': 'ē', 'θ': 'th', 'ι': 'i', 'κ': 'k', 'λ': 'l', 'μ': 'm', 'ν': 'n', 'ξ': 'x', 'ο': 'o',
       'π': 'p', 'ρ': 'r', 'σ': 's', 'ς': 's', 'τ': 't', 'υ': 'u', 'φ': 'ph', 'χ': 'ch', 'ψ': 'ps', 'ω': 'ō'}
def tr(word):
    out = []
    for ch in unicodedata.normalize('NFD', word):
        if unicodedata.category(ch) == 'Mn':
            if ch == '\u0314':   # rough breathing: 'h' before the vowel just written (ῥ -> rh)
                if out and out[-1] in ('r', 'R'): out[-1] = out[-1] + 'h'
                elif out: out[-1] = 'h' + out[-1] if out[-1].islower() else 'H' + out[-1].lower()
            continue
        lo = ch.lower(); t = MAP.get(lo, ch if not ('\u0370' <= ch <= '\u03ff' or '\u1f00' <= ch <= '\u1fff') else '')
        out.append(t.capitalize() if ch != lo and t else t)
    s = ''.join(out)
    return s
def loose(s): return ''.join(c for c in unicodedata.normalize('NFD', s) if unicodedata.category(c) != 'Mn').lower().replace('ς', 'σ')
TB = {}
for line in open(sys.argv[1], encoding='utf-8'):
    f = line.rstrip('\n').split('\t')
    if len(f) > 4 and re.match(r'^G\d{4}', f[0]): TB.setdefault(f[0], []).append((f[3], f[4]))
L = json.load(open('data/lexicon.json'))
if '--selftest' in sys.argv:   # how well do the rules reproduce the LXX entries' existing keys?
    have = [(v[0], v[3]) for v in L.values() if v[3] and ',' not in v[3]]
    ok = sum(1 for a, b in have if tr(a).lower() == b.lower())
    print('rules reproduce existing LXX keys: %d/%d = %.1f%%' % (ok, len(have), 100 * ok / len(have)))
    bad = [(a, b, tr(a)) for a, b in have if tr(a).lower() != b.lower()]; print('examples of differences:', bad[:15]); raise SystemExit
base = json.loads(subprocess.check_output(['git', 'show', '27894441:data/lexicon.json'])); FIRST = max(map(int, base)) + 1
n = {'tbesg': 0, 'rules': 0, 'already': 0}
for k, v in L.items():
    if int(k) < FIRST: continue
    if v[3]: n['already'] += 1; continue
    t = next((x[1] for x in TB.get(v[5], []) if loose(x[0]) == loose(v[0])), None)
    if t: v[3] = t.split(',')[0].strip(); n['tbesg'] += 1
    else: v[3] = tr(re.sub(r'\s*\(\d+\)$', '', v[0])); n['rules'] += 1
json.dump(L, open('data/lexicon.json', 'w'), ensure_ascii=False, separators=(',', ':'))
print('NT-only headwords (id >= %d):' % FIRST, n, 'empty keys left:', sum(1 for k, v in L.items() if int(k) >= FIRST and not v[3]))
